-- Remittance Transfer API schema (H2).
-- Money: KRW is a whole number (BIGINT). PHP has 2 decimals (DECIMAL(15,2)). See DESIGN.md Q3.

CREATE TABLE customers (
  customer_id VARCHAR(10)  PRIMARY KEY,
  name        VARCHAR(100) NOT NULL
);

CREATE TABLE transfers (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- internal key, also used to build partner_ref
  transfer_id         VARCHAR(36)   NOT NULL,                               -- public id (UUID) used in the API
  customer_id         VARCHAR(10)   NOT NULL,
  idempotency_key     VARCHAR(64)   NOT NULL,
  request_hash        VARCHAR(64)   NOT NULL,                               -- SHA-256 hex of the create request
  status              VARCHAR(16)   NOT NULL,
  send_currency       VARCHAR(3)    NOT NULL,
  send_amount         BIGINT        NOT NULL,
  fee                 BIGINT        NOT NULL,
  total_debit         BIGINT        NOT NULL,
  receive_currency    VARCHAR(3)    NOT NULL,
  fx_rate             DECIMAL(10,4) NOT NULL,                               -- rate used for this transfer
  receive_amount      DECIMAL(15,2) NOT NULL,
  recipient_name      VARCHAR(100)  NOT NULL,
  business_date       DATE          NOT NULL,                               -- creation date in Asia/Seoul (daily limit)
  partner_ref         VARCHAR(32),
  failure_reason      VARCHAR(255),
  created_at          TIMESTAMP(3) WITH TIME ZONE NOT NULL,
  updated_at          TIMESTAMP(3) WITH TIME ZONE NOT NULL,
  sending_at          TIMESTAMP(3) WITH TIME ZONE,
  partner_accepted_at TIMESTAMP(3) WITH TIME ZONE,
  completed_at        TIMESTAMP(3) WITH TIME ZONE,

  CONSTRAINT uq_transfers_transfer_id     UNIQUE (transfer_id),
  CONSTRAINT uq_transfers_idempotency_key UNIQUE (idempotency_key),
  CONSTRAINT uq_transfers_partner_ref     UNIQUE (partner_ref),
  CONSTRAINT fk_transfers_customer        FOREIGN KEY (customer_id) REFERENCES customers (customer_id),
  CONSTRAINT ck_transfers_status          CHECK (status IN ('REQUESTED', 'SENDING', 'COMPLETED', 'FAILED', 'CANCELLED')),
  CONSTRAINT ck_transfers_currencies      CHECK (send_currency = 'KRW' AND receive_currency = 'PHP'),
  CONSTRAINT ck_transfers_send_amount     CHECK (send_amount >= 10000),
  CONSTRAINT ck_transfers_fee             CHECK (fee >= 3000),
  CONSTRAINT ck_transfers_total_debit     CHECK (total_debit = send_amount + fee),
  CONSTRAINT ck_transfers_receive_amount  CHECK (receive_amount > 0 AND fx_rate > 0),
  CONSTRAINT ck_transfers_partner_ref     CHECK (status IN ('REQUESTED', 'CANCELLED') OR partner_ref IS NOT NULL),
  CONSTRAINT ck_transfers_failure_reason  CHECK (status <> 'FAILED' OR failure_reason IS NOT NULL)
);

-- Daily limit: SUM(send_amount) per customer per day. Leading column also covers the customer FK.
CREATE INDEX ix_transfers_customer_day ON transfers (customer_id, business_date);

CREATE TABLE partner_callback_events (
  event_id    VARCHAR(64) PRIMARY KEY,                                      -- makes a callback idempotent by eventId
  transfer_id BIGINT      NOT NULL,
  status      VARCHAR(16) NOT NULL,
  received_at TIMESTAMP(3) WITH TIME ZONE NOT NULL,
  CONSTRAINT fk_callback_transfer FOREIGN KEY (transfer_id) REFERENCES transfers (id),
  CONSTRAINT ck_callback_status   CHECK (status = 'COMPLETED')
);

CREATE INDEX ix_callback_transfer ON partner_callback_events (transfer_id);

